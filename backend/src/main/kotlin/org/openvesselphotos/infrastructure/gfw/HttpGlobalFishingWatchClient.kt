package org.openvesselphotos.infrastructure.gfw

import org.openvesselphotos.domain.fishing_activity.FishingActivityClient
import org.openvesselphotos.domain.fishing_activity.FishingEvent
import org.openvesselphotos.domain.fishing_activity.PortVisit
import org.openvesselphotos.domain.fishing_activity.VesselIdentity
import org.openvesselphotos.infrastructure.images.HttpImageDownloader
import org.slf4j.LoggerFactory
import org.springframework.beans.factory.annotation.Value
import org.springframework.stereotype.Component
import tools.jackson.databind.JsonNode
import tools.jackson.databind.json.JsonMapper
import java.net.URI
import java.net.URLEncoder
import java.net.http.HttpClient
import java.net.http.HttpRequest
import java.net.http.HttpResponse
import java.time.Duration
import java.time.Instant
import java.time.LocalDate
import java.util.concurrent.ConcurrentHashMap

/**
 * Global Fishing Watch API v3 (https://globalfishingwatch.org/our-apis/documentation), with the token of the app:
 * never sent to browsers, which get the tiles through this app. Data under CC BY-NC 4.0, "Powered by Global Fishing
 * Watch". 50,000 requests a day per user: tiles are kept in memory, and their style is generated once a day.
 */
@Component
class HttpGlobalFishingWatchClient(
    private val jsonMapper: JsonMapper,
    @param:Value("\${openvesselphotos.gfw-token}")
    private val token: String,
) : FishingActivityClient {
    private val logger = LoggerFactory.getLogger(HttpGlobalFishingWatchClient::class.java)
    private val client = HttpClient.newBuilder().connectTimeout(Duration.ofSeconds(15)).build()

    /** Style of the tiles of each filter and date range, generated by the API */
    private val styles = ConcurrentHashMap<String, String>()

    /** The latest tiles asked for, by URL */
    private val tiles =
        object : LinkedHashMap<String, ByteArray>(MAX_TILES, 0.75f, true) {
            override fun removeEldestEntry(eldest: MutableMap.MutableEntry<String, ByteArray>) = size > MAX_TILES
        }

    override val isEnabled: Boolean get() = token.isNotBlank()

    override fun fishingEffortTile(
        z: Int,
        x: Int,
        y: Int,
        flag: String,
        gearTypes: List<String>,
    ): ByteArray? {
        val to = LocalDate.now().withDayOfMonth(1)
        val filter =
            "flag in ('${code(flag)}')" +
                gearTypes
                    .takeIf { it.isNotEmpty() }
                    ?.let { types ->
                        " AND geartype in (${types.joinToString(",") { "'${code(it).lowercase()}'" }})"
                    }.orEmpty()
        val query =
            "interval=MONTH&datasets%5B0%5D=$FISHING_EFFORT_DATASET&filters%5B0%5D=${encode(filter)}" +
                "&date-range=${to.minusYears(1)},$to"
        val style = styles.getOrPut(query) { generateStyle(query) ?: return null }
        if (style == NO_DATA) {
            return EMPTY_TILE
        }
        val url = "$API/v3/4wings/tile/heatmap/$z/$x/$y?$query&format=PNG&temporal-aggregation=true&style=${encode(
            style,
        )}"
        synchronized(tiles) { tiles[url] }?.let { return it }

        val response = send(get(url), HttpResponse.BodyHandlers.ofByteArray())
        return when (response.statusCode()) {
            200 -> response.body().also { synchronized(tiles) { tiles[url] = it } }
            // No fishing there
            204 -> EMPTY_TILE
            else -> {
                logger.warn("Global Fishing Watch tile $z/$x/$y: HTTP ${response.statusCode()}")
                null
            }
        }
    }

    /** The style (colour ramp) of the tiles of a query, from the fishing effort of the query */
    private fun generateStyle(query: String): String? {
        val request =
            authorized("$API/v3/4wings/generate-png?color=%23${EFFORT_COLOR.removePrefix("#")}&$query")
                .POST(HttpRequest.BodyPublishers.noBody())
                .build()
        val response = send(request, HttpResponse.BodyHandlers.ofString())
        when (response.statusCode()) {
            200 -> Unit
            // No fishing recorded with this filter, e.g. dredgers, mostly too small to carry AIS
            204 -> return NO_DATA
            else -> {
                logger.warn("Global Fishing Watch style: HTTP ${response.statusCode()}")
                return null
            }
        }
        // The style is in the query of the URL of the tiles it returns
        val tileUrl = jsonMapper.readTree(response.body()).path("url").asString("")

        return URI(
            tileUrl
                .replace(" ", "%20")
                .replace("'", "%27")
                .replace("{", "%7B")
                .replace("}", "%7D"),
        ).rawQuery
            ?.split("&")
            ?.firstOrNull { it.startsWith("style=") }
            ?.removePrefix("style=")
            ?.let { java.net.URLDecoder.decode(it, Charsets.UTF_8) }
    }

    override fun findVesselIds(identity: VesselIdentity): List<String> {
        val flag = code(identity.flag)
        identity.mmsi?.let(::code)?.takeIf { it.length == MMSI_LENGTH }?.let { mmsi ->
            search("ssvid='$mmsi'") { it.path("ssvid").asString("") == mmsi }.takeIf { it.isNotEmpty() }?.let {
                return vesselIds(it)
            }
        }
        identity.callSign?.let(::code)?.takeIf { it.length >= MIN_CODE_LENGTH }?.let { callSign ->
            search("callsign='$callSign' AND flag='$flag'") {
                code(it.path("callsign").asString("")) == callSign && it.path("flag").asString("") == flag
            }.takeIf { it.isNotEmpty() }?.let { return vesselIds(it) }
        }
        // A name may be shared by several vessels: kept only when a single one has it
        val name = identity.name?.let(::code)?.takeIf { it.length >= MIN_CODE_LENGTH } ?: return emptyList()
        val entries =
            search("nShipname='$name' AND flag='$flag'") {
                it.path("nShipname").asString("") == name && it.path("flag").asString("") == flag
            }

        return if (entries.size == 1) vesselIds(entries) else emptyList()
    }

    /** The vessels matching the query, whose self-reported or registry records match [isMatching] */
    private fun search(
        where: String,
        isMatching: (JsonNode) -> Boolean,
    ): List<JsonNode> {
        val url =
            "$API/v3/vessels/search?datasets%5B0%5D=$IDENTITY_DATASET&limit=$MAX_SEARCH_RESULTS&where=${encode(where)}"
        val response = send(get(url), HttpResponse.BodyHandlers.ofString())
        check(response.statusCode() == 200) { "Global Fishing Watch vessel search: HTTP ${response.statusCode()}" }

        return jsonMapper.readTree(response.body()).path("entries").filter { entry ->
            (entry.path("selfReportedInfo") + entry.path("registryInfo")).any(isMatching)
        }
    }

    private fun vesselIds(entries: List<JsonNode>): List<String> =
        entries
            .flatMap { entry ->
                // JsonNode has a map of its own: as a list first
                val combinedIds = entry.path("combinedSourcesInfo").toList().map { it.path("vesselId").asString("") }
                val selfReportedIds = entry.path("selfReportedInfo").toList().map { it.path("id").asString("") }
                combinedIds + selfReportedIds
            }.filter { it.isNotBlank() }
            .distinct()

    override fun findPortVisits(
        vesselIds: List<String>,
        from: LocalDate,
        to: LocalDate,
    ): List<PortVisit> {
        if (vesselIds.isEmpty()) {
            return emptyList()
        }
        val visits = mutableListOf<PortVisit>()
        var offset: Int? = 0
        while (offset != null && offset < MAX_PORT_VISITS) {
            val url =
                "$API/v3/events?datasets%5B0%5D=$PORT_VISITS_DATASET" +
                    vesselIds.mapIndexed { index, id -> "&vessels%5B$index%5D=${encode(id)}" }.joinToString("") +
                    "&start-date=$from&end-date=$to&confidences%5B0%5D=3&confidences%5B1%5D=4" +
                    "&limit=$PORT_VISITS_PAGE&offset=$offset"
            val response = send(get(url), HttpResponse.BodyHandlers.ofString())
            check(response.statusCode() == 200) { "Global Fishing Watch port visits: HTTP ${response.statusCode()}" }
            val page = jsonMapper.readTree(response.body())
            page.path("entries").forEach { entry ->
                val anchorage = entry.path("port_visit").path("startAnchorage")
                val id = anchorage.path("id").asString("")
                if (id.isNotBlank() && anchorage.has("lat") && anchorage.has("lon")) {
                    visits +=
                        PortVisit(
                            portId = id,
                            // The name is null for some ports, e.g. fra-lorient
                            portName =
                                anchorage.path("name").takeUnless { it.isNull || it.isMissingNode }?.asString() ?: id,
                            portFlag = anchorage.path("flag").asString("").ifBlank { null },
                            latitude = anchorage.path("lat").asDouble(),
                            longitude = anchorage.path("lon").asDouble(),
                        )
                }
            }
            offset = page.path("nextOffset").takeIf { it.isNumber }?.asInt()
        }

        return visits
    }

    override fun findFishingEvents(
        vesselIds: List<String>,
        from: LocalDate,
        to: LocalDate,
    ): List<FishingEvent> {
        if (vesselIds.isEmpty()) {
            return emptyList()
        }
        val events = mutableListOf<FishingEvent>()
        var offset: Int? = 0
        while (offset != null && offset < MAX_FISHING_EVENTS) {
            val url =
                "$API/v3/events?datasets%5B0%5D=$FISHING_EVENTS_DATASET" +
                    vesselIds.mapIndexed { index, id -> "&vessels%5B$index%5D=${encode(id)}" }.joinToString("") +
                    "&start-date=$from&end-date=$to&limit=$EVENTS_PAGE&offset=$offset"
            val response = send(get(url), HttpResponse.BodyHandlers.ofString())
            check(response.statusCode() == 200) { "Global Fishing Watch fishing events: HTTP ${response.statusCode()}" }
            val page = jsonMapper.readTree(response.body())
            page.path("entries").forEach { entry ->
                val position = entry.path("position")
                val start = entry.path("start").asString("")
                val end = entry.path("end").asString("")
                if (position.has("lat") && position.has("lon") && start.isNotEmpty() && end.isNotEmpty()) {
                    val hours = Duration.between(Instant.parse(start), Instant.parse(end)).toMinutes() / 60.0
                    events += FishingEvent(position.path("lat").asDouble(), position.path("lon").asDouble(), hours)
                }
            }
            offset = page.path("nextOffset").takeIf { it.isNumber }?.asInt()
        }

        return events
    }

    private fun get(url: String): HttpRequest = authorized(url).GET().build()

    private fun authorized(url: String): HttpRequest.Builder =
        HttpRequest
            .newBuilder(URI(url))
            .timeout(Duration.ofSeconds(60))
            .header("Authorization", "Bearer $token")
            // The API refuses the requests without a client name
            .header("User-Agent", HttpImageDownloader.USER_AGENT)

    /** Sends the request, waiting and trying again when rate limited */
    private fun <T> send(
        request: HttpRequest,
        handler: HttpResponse.BodyHandler<T>,
    ): HttpResponse<T> {
        check(isEnabled) { "No Global Fishing Watch token (OPENVESSELPHOTOS_GFW_TOKEN)." }
        repeat(MAX_ATTEMPTS - 1) { attempt ->
            val response = client.send(request, handler)
            if (response.statusCode() != 429) {
                return response
            }
            Thread.sleep(RATE_LIMIT_WAIT_MS * (attempt + 1))
        }

        return client.send(request, handler)
    }

    /** Letters and digits only, upper case: what the API compares, and nothing that could change a query */
    private fun code(value: String): String = value.uppercase().replace(Regex("[^A-Z0-9]"), "")

    private fun encode(value: String): String = URLEncoder.encode(value, Charsets.UTF_8).replace("+", "%20")

    private operator fun JsonNode.plus(other: JsonNode): List<JsonNode> = toList() + other.toList()

    companion object {
        private const val API = "https://gateway.api.globalfishingwatch.org"
        private const val FISHING_EFFORT_DATASET = "public-global-fishing-effort:latest"
        private const val IDENTITY_DATASET = "public-global-vessel-identity:latest"
        private const val PORT_VISITS_DATASET = "public-global-port-visits-events:latest"
        private const val FISHING_EVENTS_DATASET = "public-global-fishing-events:latest"
        private const val MAX_FISHING_EVENTS = 5_000
        private const val EVENTS_PAGE = 200
        private const val MAX_TILES = 600
        private const val MAX_SEARCH_RESULTS = 10
        private const val MAX_PORT_VISITS = 1_000
        private const val PORT_VISITS_PAGE = 200
        private const val MAX_ATTEMPTS = 3
        private const val RATE_LIMIT_WAIT_MS = 30_000L
        private const val MMSI_LENGTH = 9
        private const val MIN_CODE_LENGTH = 3

        /** Teal: apart from the navy of the ports on the map */
        const val EFFORT_COLOR = "#0B9B96"

        /** The style of a query without data */
        private const val NO_DATA = ""

        /** A transparent 1 px PNG, for the tiles without fishing */
        val EMPTY_TILE: ByteArray =
            java.util.Base64.getDecoder().decode(
                "iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAYAAAAfFcSJAAAADUlEQVR42mNkYPhfDwAChwGA60e6kgAAAABJRU5ErkJggg==",
            )
    }
}
